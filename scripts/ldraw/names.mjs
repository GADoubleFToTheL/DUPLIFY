const ESC = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const DICT = new Map(WORDS);
const KEYS = [...DICT.keys()].sort((a, b) => b.length - a.length);
const RE = new RegExp(`(^|[^A-Za-z])(${KEYS.map(ESC).join('|')})(?=$|[^A-Za-z])`, 'g');

const translate = (s) => s.replace(RE, (_, pre, w) => `${pre}${DICT.get(w)}`);

export function translateName(en) {
  let s = en.replace(/^Duplo\s+(Primo\s+)?/, (_, primo) => (primo ? 'Primo ' : ''));
  // „… with Red Heart Pattern“ → „…, Aufdruck: rot Herz“
  let print = '';
  const m = s.includes(',') ? null : s.match(/^(.*?)\s+with\s+((?:(?!\bwith\b).)+?)\s+Pattern$/);
  if (m) {
    s = m[1];
    print = m[2];
  }
  let out = translate(` ${s} `);
  if (print) out = `${out.trim()}, Aufdruck: ${translate(` ${print} `).trim()}`;
  out = out
    .replace(/\s+/g, ' ')
    .replace(/\s+,/g, ',')
    .replace(/(\d)\s+x\s+(\d)/g, '$1 x $2')
    .trim();
  return out.charAt(0).toUpperCase() + out.slice(1);
}

const has = (en, ...words) => words.some((w) => new RegExp(`\\b${w}\\b`, 'i').test(en));

export function categorize(en) {
  if (has(en, 'Train', 'Rail', 'Track', 'Locomotive')) return 'zug';
  if (has(en, 'Car', 'Wheel', 'Wheels', 'Tyre', 'Axle', 'Truck', 'Boat', 'Aeroplane', 'Airplane', 'Plane', 'Tractor', 'Trailer', 'Dumper', 'Crane', 'Helicopter', 'Vehicle', 'Bike', 'Motorcycle'))
    return 'fahrzeuge';
  if (has(en, 'Door', 'Window', 'Shutter', 'Pane')) return 'fenster';
  if (has(en, 'Building', 'House', 'Garage', 'Wall', 'Pillar', 'Column', 'Support', 'Stairs', 'Ladder')) return 'gebaeude';
  if (has(en, 'Plant', 'Flower', 'Tree', 'Palm', 'Leaves', 'Fence', 'Furniture', 'Animal')) return 'zubehoer';
  if (has(en, 'Baseplate', 'Plate', 'Tile')) return 'platten';
  if (has(en, 'Slope', 'Roof', 'Spire')) return 'dach';
  if (has(en, 'Arch', 'Curved', 'Cone', 'Cylinder', 'Round', 'Dome')) return 'boegen';
  if (has(en, 'Brick', 'Primo')) return 'steine';
  return 'zubehoer';
}

export function classify(en, m) {
  if (m.ground && has(en, 'Car', 'Wheel', 'Wheels', 'Truck', 'Train', 'Vehicle', 'Chassis')) return 'vehicle';
  if (has(en, 'Baseplate', 'Plate', 'Tile')) return 'plate';
  if (has(en, 'Door Frame', 'Window', 'Door')) return 'frame';
  if (has(en, 'Arch')) return 'arch';
  if (has(en, 'Slope', 'Roof')) return 'slope';
  if (has(en, 'Curved')) return 'curved';
  if (m.studs !== 'all' && m.studs.length === 0) return 'deco';
  return 'brick';
}
